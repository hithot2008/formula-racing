export const angle = (a) => Math.atan2(Math.sin(a), Math.cos(a));
export const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
export function makeTrack(def) {
  const curve = new THREE.CatmullRomCurve3(
    def.points.map(([x, z]) => new THREE.Vector3(x, 0, z)),
    true,
    'centripetal',
  );
  curve.arcLengthDivisions = 2400;
  const length = curve.getLength(),
    count = 900;
  const samples = Array.from({ length: count }, (_, i) => {
    const p = curve.getPointAt(i / count),
      t = curve.getTangentAt(i / count).normalize();
    return {
      x: p.x,
      z: p.z,
      tx: t.x,
      tz: t.z,
      heading: Math.atan2(t.x, t.z),
      s: (i / count) * length,
    };
  });
  const at = (s) => {
    const f = ((((s % length) + length) % length) / length) * count,
      i = Math.floor(f),
      a = samples[i],
      b = samples[(i + 1) % count],
      u = f - i;
    return {
      x: a.x + (b.x - a.x) * u,
      z: a.z + (b.z - a.z) * u,
      heading: a.heading + angle(b.heading - a.heading) * u,
      tx: a.tx + (b.tx - a.tx) * u,
      tz: a.tz + (b.tz - a.tz) * u,
    };
  };
  const nearest = (x, z) => {
    let best = Infinity,
      index = 0;
    for (let i = 0; i < count; i++) {
      const a = samples[i],
        d = (x - a.x) ** 2 + (z - a.z) ** 2;
      if (d < best) {
        best = d;
        index = i;
      }
    }
    const a = samples[index],
      b = samples[(index + 1) % count],
      dx = b.x - a.x,
      dz = b.z - a.z;
    const u = clamp(((x - a.x) * dx + (z - a.z) * dz) / (dx * dx + dz * dz), 0, 1);
    const px = a.x + dx * u,
      pz = a.z + dz * u;
    return {
      s: ((index + u) / count) * length,
      lateral: (x - px) * a.tz - (z - pz) * a.tx,
      distance: Math.hypot(x - px, z - pz),
      ...at(((index + u) / count) * length),
    };
  };
  return {
    ...def,
    curve,
    length,
    samples,
    at,
    nearest,
    curvature: (s) => angle(at(s + 8).heading - at(s - 8).heading) / 16,
  };
}
